const sleep = promisify(setTimeout);

// Helper to create mock lockfile for testing when pip-compile is unavailable
const createMockLockfile = (filePath: string, packages: string[] = []): void => {
  const header = '# This file is autogenerated by pip-compile with Python 3.10\n#\n';
  const packageLines = packages.length > 0 
    ? packages.join('\n')
    : 'numpy==1.24.3\ntorch==2.0.1\ntransformers==4.30.2';
  fs.writeFileSync(filePath, header + packageLines + '\n');
};

// Check if pip-compile is available
const checkPipCompileAvailable = (): boolean => {
  try {
    const { execSync } = require('child_process');
    execSync('python3 -m pip show pip-tools', { stdio: 'pipe' });
    return true;
  } catch {
    return false;
  }
};

const pipCompileAvailable = checkPipCompileAvailable();

