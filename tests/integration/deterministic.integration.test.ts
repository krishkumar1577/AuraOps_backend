  jest.setTimeout(30000);

  let tempDir: string;
  let dependencyLocker: DependencyLocking;
  let hashVerifier: HashVerifier;

  // Test fixture data
  const simpleRequirements = `numpy==1.24.3
torch==2.0.1
transformers==4.30.2`;

  const complexRequirements = `numpy==1.24.3
torch==2.0.1
transformers==4.30.2
langchain==0.0.225
pydantic>=1.9.0,<2.0.0
requests
python-dotenv`;

