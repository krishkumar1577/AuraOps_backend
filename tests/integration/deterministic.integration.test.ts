      // Arrange
      const lockPath = path.join(tempDir, 'verify-hash-lock.txt');
      createMockLockfile(lockPath);

      // Act
      const hash = await hashVerifier.hashEnvironment(lockPath);
      const isValid = await hashVerifier.verifyLockfile(lockPath, hash);

